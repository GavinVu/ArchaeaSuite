// Generates src/ArchaeaPhoto/Icons.g.cs from the Lucide icon set the launcher
// already uses (ISC licence), so both apps share one icon language.
//   node apps/ArchaeaPhoto/tools/make-icons.mjs      (after `npm ci` in launcher/)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const lucide = resolve(here, "../../../launcher/node_modules/lucide-react/dist/esm/icons");

// C# name -> lucide file name
const icons = {
  Move: "move", RectSelect: "square-dashed", EllipseSelect: "circle-dashed", Lasso: "lasso",
  Wand: "wand-sparkles", Crop: "crop", Eyedropper: "pipette", Brush: "brush", Eraser: "eraser",
  Stamp: "stamp", Bucket: "paint-bucket", Text: "type", Shape: "shapes", Hand: "hand", Zoom: "search",
  Eye: "eye", EyeOff: "eye-off", Plus: "plus", Trash: "trash-2", Copy: "copy", Folder: "folder",
  FolderOpen: "folder-open", Layers: "layers", ChevronRight: "chevron-right", ChevronDown: "chevron-down",
  Close: "x", Undo: "undo-2", Redo: "redo-2", ArrowUp: "arrow-up", ArrowDown: "arrow-down",
  Swap: "arrow-left-right", Image: "image", Check: "check", Minus: "minus", Square: "square",
  Maximize: "square", Restore: "copy", Transform: "scaling", Reset: "rotate-ccw", Sliders: "sliders-horizontal",
  Sun: "sun", Moon: "moon", TextCursor: "text-cursor", Merge: "merge",
};

const n = (v) => Number(v);
function toPath([tag, a]) {
  switch (tag) {
    // A leading relative "m" is absolute in its own element, but the pairs after it stay relative lines.
    case "path": return a.d.replace(/^m\s*(-?\d*\.?\d+)[\s,]*(-?\d*\.?\d+)\s*(?=([-\d.])?)/,(_, x, y, more) => `M${x} ${y}${more ? "l" : ""}`);
    case "circle": { const cx = n(a.cx), cy = n(a.cy), r = n(a.r);
      return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0Z`; }
    case "ellipse": { const cx = n(a.cx), cy = n(a.cy), rx = n(a.rx), ry = n(a.ry);
      return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0Z`; }
    case "line": return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case "polyline": case "polygon": {
      const pts = a.points.trim().split(/[\s,]+/).map(Number);
      let d = `M${pts[0]} ${pts[1]}`;
      for (let i = 2; i < pts.length; i += 2) d += `L${pts[i]} ${pts[i + 1]}`;
      return tag === "polygon" ? d + "Z" : d; }
    case "rect": { const x = n(a.x ?? 0), y = n(a.y ?? 0), w = n(a.width), h = n(a.height);
      const r = Math.min(n(a.rx ?? a.ry ?? 0), w / 2, h / 2);
      if (!r) return `M${x} ${y}h${w}v${h}h${-w}Z`;
      return `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z`; }
    default: throw new Error("unsupported element " + tag);
  }
}

let out = "// <auto-generated> by tools/make-icons.mjs from lucide (ISC). Do not edit. </auto-generated>\nnamespace ArchaeaPhoto;\n\npublic static partial class Icons\n{\n";
for (const [name, file] of Object.entries(icons)) {
  const src = readFileSync(resolve(lucide, file + ".js"), "utf8");
  const start = src.indexOf("[", src.indexOf("createLucideIcon("));
  const end = src.lastIndexOf("]");
  const nodes = new Function("return " + src.slice(start, end + 1))();
  out += `    public const string ${name} = "${nodes.map(toPath).join(" ")}";\n`;
}
// Not in lucide: a gradient ramp and a layer-mask glyph, drawn on the same 24px grid.
out += `    public const string Gradient = "M3 5h18v14h-18Z M7 5v14 M11 5v14 M15 9v6 M18.5 11v2";\n`;
out += `    public const string Mask = "M3 5h18v14h-18Z M8 12a4 4 0 1 0 8 0a4 4 0 1 0 -8 0Z";\n`;
out += "}\n";
writeFileSync(resolve(here, "../src/ArchaeaPhoto/Icons.g.cs"), out);
console.log("icons:", Object.keys(icons).length + 2);
